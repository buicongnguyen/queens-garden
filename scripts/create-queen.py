"""Run with Blender --background --python scripts/create-queen.py.
Creates editable source, GLB, shared game geometry, and transparent token render.
"""
import bpy
import math
import json
from pathlib import Path
from mathutils import Vector

ROOT = Path(__file__).resolve().parent.parent
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)

def material(name, color, metallic, roughness):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1)
    mat.use_nodes = True
    shader = mat.node_tree.nodes.get('Principled BSDF')
    shader.inputs['Base Color'].default_value = (*color, 1)
    shader.inputs['Metallic'].default_value = metallic
    shader.inputs['Roughness'].default_value = roughness
    shader.inputs['Coat Weight'].default_value = .28
    shader.inputs['Coat Roughness'].default_value = .18
    return mat

ivory = material('Warm porcelain', (.82, .73, .55), .03, .23)
gold = material('Brushed champagne gold', (.62, .37, .11), .85, .24)
emerald = material('Polished jade', (.015, .15, .095), .32, .16)
parts = []

def lathe(name, profile, mat):
    segments = 64
    verts = [(r*math.cos(2*math.pi*j/segments), r*math.sin(2*math.pi*j/segments), z)
             for r,z in profile for j in range(segments)]
    faces = []
    for k in range(len(profile)-1):
        for j in range(segments):
            a=k*segments+j; b=k*segments+(j+1)%segments
            faces.append((a,b,b+segments,a+segments))
    mesh=bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces); mesh.update()
    obj=bpy.data.objects.new(name,mesh); bpy.context.collection.objects.link(obj)
    obj.data.materials.append(mat)
    for poly in mesh.polygons: poly.use_smooth=True
    parts.append(obj)
    return obj

lathe('Queen base and sculpted body', [
    (0,.015),(.235,.015),(.275,.025),(.297,.05),(.3,.075),(.294,.10),
    (.276,.12),(.266,.14),(.27,.17),(.263,.20),(.24,.23),(.208,.25),
    (.188,.28),(.175,.32),(.159,.38),(.14,.45),(.123,.53),(.115,.60),
    (.119,.67),(.132,.73),(.155,.78),(.18,.81),(.215,.83),(.23,.85),
    (.232,.875),(.215,.90),(.19,.918),(.166,.95),(.15,.985),(0,.985)], ivory)
for name,z,r in [('Foot inlay',.13,.27),('Base beading',.205,.251),('Neck collar',.89,.218)]:
    lathe(name,[(r-.025,z-.012),(r,z-.012),(r+.009,z),(r,z+.013),(r-.025,z+.013),(r-.025,z-.012)],gold)
lathe('Royal crown cup',[(0,.955),(.145,.955),(.153,.975),(.167,1.01),
    (.197,1.05),(.225,1.095),(.229,1.115),(.217,1.13),(.192,1.12),
    (.175,1.08),(.15,1.03),(.12,1.01),(0,1.01)],gold)
lathe('Jade crown cushion',[(0,1.00),(.14,1.00),(.162,1.035),(.16,1.075),
    (.136,1.105),(.09,1.125),(0,1.13)],emerald)

for j in range(8):
    a=2*math.pi*j/8
    x,y=.215*math.cos(a),.215*math.sin(a)
    bpy.ops.mesh.primitive_uv_sphere_add(segments=16,ring_count=8,radius=.043,location=(x,y,1.16))
    obj=bpy.context.object; obj.name=f'Crown pearl {j+1}'; obj.scale=(.78,.78,1.35)
    obj.data.materials.append(gold)
    for poly in obj.data.polygons: poly.use_smooth=True
    parts.append(obj)
lathe('Central finial',[(0,1.105),(.05,1.105),(.055,1.14),(.032,1.18),
    (.024,1.23),(.045,1.25),(.056,1.28),(.045,1.315),(0,1.335)],ivory)

# Consolidate by material for efficient browser draw calls and portable export.
templates=[]
for mat, color in [(ivory,'#eadfc4'),(gold,'#cea45d'),(emerald,'#226c56')]:
    bpy.ops.object.select_all(action='DESELECT')
    group=[o for o in bpy.context.scene.objects if o.type == 'MESH' and o.data.materials[0] == mat]
    for obj in group: obj.select_set(True)
    bpy.context.view_layer.objects.active=group[0]
    bpy.ops.object.join()
    obj=bpy.context.object
    obj.name={'Warm porcelain':'Queen base porcelain','Brushed champagne gold':'Queen gold detailing','Polished jade':'Queen jade cushion'}[mat.name]
    bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
    mesh=obj.data; mesh.calc_loop_triangles()
    positions=[]; normals=[]
    normal_matrix=obj.matrix_world.to_3x3().inverted().transposed()
    for v in mesh.vertices:
        p=obj.matrix_world @ v.co; n=(normal_matrix @ v.normal).normalized()
        if n.length < .5: n=Vector((0,0,1))
        positions.extend([round(p.x,6),round(p.z,6),round(-p.y,6)])
        normals.extend([round(n.x,6),round(n.z,6),round(-n.y,6)])
    shader=mat.node_tree.nodes.get('Principled BSDF')
    templates.append(dict(name=obj.name,positions=positions,normals=normals,
        indices=[i for tri in mesh.loop_triangles for i in tri.vertices],color=color,
        metallic=shader.inputs['Metallic'].default_value,
        roughness=shader.inputs['Roughness'].default_value))

(ROOT/'src/queen-model.js').write_text('// Generated by Blender; rebuild with scripts/create-queen.py.\nexport const QUEEN_MODEL = '+json.dumps(templates,separators=(',',':'))+';\n',encoding='utf8')
bpy.ops.object.select_all(action='DESELECT')
for obj in bpy.context.scene.objects:
    if obj.type == 'MESH': obj.select_set(True)
bpy.ops.export_scene.gltf(filepath=str(ROOT/'assets/queen-real.glb'),export_format='GLB',use_selection=True)

def aim(obj, point): obj.rotation_euler=(Vector(point)-obj.location).to_track_quat('-Z','Y').to_euler()
bpy.ops.object.camera_add(location=(2.5,-4,2.4))
cam=bpy.context.object; aim(cam,(0,0,.66)); cam.data.type='ORTHO'; cam.data.ortho_scale=1.58
bpy.context.scene.camera=cam
for name,loc,power,size in [('Key',(-3,-4,5),450,3),('Fill',(3,-1,2.5),180,2),('Rim',(1,3,4),600,2)]:
    bpy.ops.object.light_add(type='AREA',location=loc)
    light=bpy.context.object; light.name=name; light.data.energy=power; light.data.shape='DISK'; light.data.size=size; aim(light,(0,0,.6))
scene=bpy.context.scene
scene.world.color=(.18,.18,.18)
scene.render.engine='CYCLES'; scene.cycles.samples=48
scene.render.resolution_x=384; scene.render.resolution_y=384; scene.render.resolution_percentage=100
scene.render.film_transparent=True
scene.render.image_settings.file_format='PNG'; scene.render.image_settings.color_mode='RGBA'
scene.render.filepath=str(ROOT/'assets/queen-token-real.png')
bpy.ops.wm.save_as_mainfile(filepath=str(ROOT/'assets/queen-source.blend'))
bpy.ops.render.render(write_still=True)
print('QUEEN_ASSETS_COMPLETE',sum(len(t['positions'])//3 for t in templates),'vertices')
